// Downloads Noto Serif Black cut down to the Chinese, Japanese and Korean
// characters in the /new-name lists, so CJK names can use a heavy serif close to
// Bevan without loading whole CJK fonts. Google Fonts does the cutting through its
// `text` parameter. Run `bun run fonts:cjk` after changing those lists, and commit
// the fonts in public/fonts and app/utils/cjk-font-glyphs.ts.

import { writeFile } from "node:fs/promises";
import { cjkGlyphs, cjkFonts } from "../app/utils/cjk-fonts";

// Google Fonts only serves woff2 to browsers it recognises.
const userAgent =
   "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

const glyphs = cjkGlyphs();

for (const font of cjkFonts) {
   const text = glyphs[font.lang];
   const cssUrl = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(
      font.googleFamily,
   )}:wght@900&text=${encodeURIComponent(text)}`;
   const css = await (
      await fetch(cssUrl, { headers: { "User-Agent": userAgent } })
   ).text();
   const fontUrl = /url\((https:[^)]+)\)/.exec(css)?.[1];
   if (fontUrl == null) throw new Error(`No font URL for ${font.lang}:\n${css}`);
   const data = await (await fetch(fontUrl)).arrayBuffer();
   await writeFile(`public${font.file}`, new Uint8Array(data));
   console.log(`${font.file}: ${Array.from(text).length} characters, ${data.byteLength} bytes`);
}

await writeFile(
   "app/utils/cjk-font-glyphs.ts",
   `// Generated by scripts/subset-cjk-fonts.ts. The characters each font in
// public/fonts was cut down to.
export const cjkFontGlyphs: Record<string, string> = ${JSON.stringify(glyphs, null, 3)};
`,
);
