/**
 * Original US broadcast dates for the Star Trek series tracked on /startrek,
 * in order, grouped by season.
 *
 * Generated from the TVmaze API and checked against the canonical episode
 * counts (79 / 178 / 176 / 172 / 98). The gaps are uneven on purpose: every one
 * of these shows took long mid-season breaks and skipped odd weeks. Dates for
 * the syndicated shows (TNG, DS9, VOY) are the usual cited broadcast dates;
 * because they were sold market by market, other sources sometimes differ by a
 * few days.
 *
 * A third tuple element is how many episode slots one broadcast filled, for the
 * feature-length premieres and finales that ran as a single night's television.
 */
export type EpisodeRecord = [
   originalAirDate: string,
   title: string,
   episodeSlots?: number,
];

export interface SeriesData {
   id: string;
   /** Fan abbreviation, used for the series tabs. */
   shortName: string;
   name: string;
   fullName: string;
   /** How far behind the original run we are watching it. */
   delayYears: number;
   seasons: Array<Array<EpisodeRecord>>;
}

